def main(argv: list[str]) -> int:
    out_dir = Path(argv[1]) if len(argv) > 1 else Path(__file__).parent / "samples"
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, content in SAMPLES.items():
        target = out_dir / name
        target.write_text(content, encoding="utf-8", newline="\n")
        print(f"已生成：{target}")
    print(f"\n共 {len(SAMPLES)} 份样例。建议接着跑：")
    print(f'  python scripts/contract_toolkit.py parse "{out_dir}" 台账.xlsx')
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
